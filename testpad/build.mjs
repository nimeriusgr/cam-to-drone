// Embeds ../edge/agent.py into lib/edge_agent.js so boxes connected to the test site can be updated from the admin page.
// Run before deploying:  node build.mjs && npx wrangler pages deploy
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const agent = readFileSync(join(here, '..', 'edge', 'agent.py'));
const version = (agent.toString('utf8').match(/^VERSION\s*=\s*"([^"]+)"/m) || [])[1] || '?';
const sha256 = createHash('sha256').update(agent).digest('hex');
writeFileSync(join(here, 'lib', 'edge_agent.js'), `// generated by build.mjs from edge/agent.py, do not edit
export const AGENT = ${JSON.stringify({ version, sha256, code: agent.toString('utf8') })};
`);
console.log(`edge agent ${version} embedded`);
