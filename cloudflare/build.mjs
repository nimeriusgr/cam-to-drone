// Copies the console UI from ../server/static into ./public (one source of truth for both servers)
// and embeds ../edge/agent.py into the Functions bundle, so edge boxes can update themselves.
import { cpSync, mkdirSync, rmSync, writeFileSync, copyFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'server', 'static');
const out = join(here, 'public');
rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'static'), { recursive: true });
cpSync(src, join(out, 'static'), { recursive: true });
copyFileSync(join(src, 'index.html'), join(out, 'index.html'));
// the service worker must be served from the root to control the whole site
copyFileSync(join(src, 'sw.js'), join(out, 'sw.js'));
copyFileSync(join(src, 'manifest.webmanifest'), join(out, 'manifest.webmanifest'));
writeFileSync(join(out, '_routes.json'), JSON.stringify({ version: 1, include: ['/api/*', '/webhook/*', '/media/*', '/report/*'], exclude: [] }, null, 2));
writeFileSync(join(out, '_headers'), `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
/sw.js
  Cache-Control: no-cache
/manifest.webmanifest
  Content-Type: application/manifest+json
`);

const agent = readFileSync(join(here, '..', 'edge', 'agent.py'));
const version = (agent.toString('utf8').match(/^VERSION\s*=\s*"([^"]+)"/m) || [])[1] || '?';
const sha256 = createHash('sha256').update(agent).digest('hex');
writeFileSync(join(here, 'lib', 'edge_agent.js'), `// generated by build.mjs from edge/agent.py, do not edit
export const AGENT = ${JSON.stringify({ version, sha256, code: agent.toString('utf8') })};
`);
console.log(`public/ ready · edge agent ${version}`);
